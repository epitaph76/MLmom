import { spawn } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { python, root } from './config.mjs';

const check = process.argv.includes('--check');
await new Promise((resolve, reject) => {
  const child = spawn(python, ['-m', 'mlmom.export_contracts', ...(check ? ['--check'] : [])], { cwd: root, stdio: 'inherit' });
  child.on('error', reject);
  child.on('exit', code => code === 0 ? resolve() : reject(new Error('Contract export failed')));
});
for (const name of ['research', 'backend']) {
  const source = new URL(`../contracts/${name}.openapi.json`, import.meta.url);
  const content = '// Generated by npm run contracts; do not edit.\n' + astToString(await openapiTS(source));
  const target = path.join(root, 'packages/pi/src', `${name}.generated.ts`);
  if (check) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Stale ${name} types; run npm run contracts`);
  } else await writeFile(target, content);
}
